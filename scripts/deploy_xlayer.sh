#!/usr/bin/env bash
# X Layer (TapeOut Accelerate) — one-shot deploy + frontend wiring for SafeShamba.
#
#   ./scripts/deploy_xlayer.sh --network xlayer        # mainnet, chain 196
#   ./scripts/deploy_xlayer.sh --network xlayerTestnet # testnet, chain 1952
#
# Reads the key material from a local, git-ignored file:  safeshamba-xlayer/.env.xlayer
#   PRIVATE_KEY=0x...              (deployer)
#   NOTARY_PRIVATE_KEY=0x...       (optional — separate notary wallet)
#   TREASURY_PRIVATE_KEY=0x...     (optional — separate treasury wallet)
#   SELLER_PRIVATE_KEY=0x...       (optional — separate seller wallet)
#
# What it does:
#   1. checks the deployer balance on the target chain (needs a little OKB)
#   2. runs scripts/deploy.js (deploys MultiSigWallet + NotaryMediatedEscrow + EscrowFactory,
#      creates a demo escrow and walks the full 4-phase workflow on-chain)
#   3. writes the deployed addresses into app/.env (VITE_FACTORY_ADDRESS / VITE_ESCROW_ADDRESS)
#   4. builds the frontend and prints the Google-Form-ready summary (addresses + explorer links)

set -euo pipefail
cd "$(dirname "$0")/.."
REPO="$(pwd)"

NET="xlayer"
while [[ $# -gt 0 ]]; do
  case "$1" in
    --network) NET="$2"; shift 2 ;;
    *) echo "unknown arg: $1"; exit 2 ;;
  esac
done

case "$NET" in
  xlayer)        CHAIN_ID=196;  EXPL="https://www.oklink.com/xlayer"; RPC="${XLAYER_RPC:-https://rpc.xlayer.tech}" ;;
  xlayerTestnet) CHAIN_ID=1952; EXPL="https://www.oklink.com/xlayer-test"; RPC="${XLAYER_TESTNET_RPC:-https://testrpc.xlayer.tech}" ;;
  *) echo "network must be xlayer or xlayerTestnet"; exit 2 ;;
esac

ENVFILE="$REPO/.env.xlayer"
if [[ -f "$ENVFILE" ]]; then
  set -a; source "$ENVFILE"; set +a
else
  echo "ERROR: missing $ENVFILE"
  cat <<'EOF'

  Create it (NOT committed — .gitignore already covers .env.*):
    printf 'PRIVATE_KEY=0xYOUR_DEPLOYER_KEY\n' > .env.xlayer
    chmod 600 .env.xlayer

  Use a dedicated low-value wallet for this hackathon; fund it with a small
  amount of OKB on the target chain (mainnet 196 / testnet 1952).
  Optional role wallets (separate notary / treasury / seller) make the
  2-of-3 multisig demo credible:
    NOTARY_PRIVATE_KEY=0x...
    TREASURY_PRIVATE_KEY=0x...
    SELLER_PRIVATE_KEY=0x...
EOF
  exit 1
fi

if [[ -z "${PRIVATE_KEY:-}" ]]; then echo "ERROR: PRIVATE_KEY not set in $ENVFILE"; exit 1; fi

echo "==> network: $NET (chain $CHAIN_ID) via $RPC"
export XLAYER_RPC="$RPC" XLAYER_TESTNET_RPC="$RPC"

# --- balance check -----------------------------------------------------------
BAL=$(node -e "
const {JsonRpcProvider, Wallet, formatEther} = require('ethers');
(async()=>{
  const p = new JsonRpcProvider('$RPC');
  const w = new Wallet(process.env.PRIVATE_KEY, p);
  const b = await p.getBalance(w.address);
  console.log(w.address + '|' + formatEther(b));
})().catch(e=>{console.error('RPC_ERROR: '+e.message);process.exit(1)});
")
ADDR="${BAL%%|*}"; BALANCE="${BAL##*|}"
echo "==> deployer: $ADDR  balance: $BALANCE OKB"
if awk "BEGIN{exit !($BALANCE < 0.002)}"; then
  echo "ERROR: deployer balance looks too low for a mainnet deploy. Top up OKB and re-run."
  exit 1
fi

# --- deploy + demo workflow --------------------------------------------------
echo "==> compiling…"
npx hardhat compile

echo "==> deploying (this also walks the 4-phase escrow workflow on-chain)…"
LOG="$(mktemp)"
npx hardhat run scripts/deploy.js --network "$NET" | tee "$LOG"

extract() { grep -Eo "$1 deployed to: 0x[0-9a-fA-F]{40}" "$LOG" | grep -Eo "0x[0-9a-fA-F]{40}" | tail -1; }
MULTISIG="$(extract 'MultiSigWallet')"
ESCROW="$(extract 'NotaryMediatedEscrow')"
FACTORY="$(extract 'EscrowFactory')"
TESTESCROW="$(grep -Eo 'Test escrow contract deployed at: 0x[0-9a-fA-F]{40}' "$LOG" | grep -Eo '0x[0-9a-fA-F]{40}' | tail -1 || true)"

if [[ -z "$FACTORY" || -z "$ESCROW" ]]; then
  echo "ERROR: could not parse deployed addresses from the log (see $LOG)"; exit 1
fi

# --- wire the frontend ------------------------------------------------------
echo "==> writing app/.env"
python3 - "$REPO" "$CHAIN_ID" "$FACTORY" "$ESCROW" "$MULTISIG" <<'PY'
import sys, pathlib
repo, chain, factory, escrow, multisig = sys.argv[1:6]
p = pathlib.Path(repo) / "app" / ".env"
existing = p.read_text() if p.exists() else ""
lines, seen = [], set()
def put(k, v):
    if k in seen: return
    seen.add(k); lines.append(f"{k}={v}")
put("VITE_XLAYER_CHAIN_ID", chain)
put("VITE_FACTORY_ADDRESS", factory)
put("VITE_ESCROW_ADDRESS", escrow)
put("VITE_MULTISIG_ADDRESS", multisig)
for ln in existing.splitlines():
    if "=" in ln:
        k, v = ln.split("=", 1)
        if k.startswith("VITE_") and k not in seen and v.strip():
            lines.append(f"{k}={v}")
p.write_text("# X Layer TapeOut Accelerate — generated by scripts/deploy_xlayer.sh\n" + "\n".join(lines) + "\n")
print(p.read_text())
PY

echo "==> building the frontend"
( cd app && npm run build )

cat <<EOF

================ DEPLOY SUMMARY (chain $CHAIN_ID) ================
EscrowFactory     $FACTORY
NotaryMediatedEscrow $ESCROW
MultiSigWallet    $MULTISIG
Demo escrow       ${TESTESCROW:-n/a}

Explorer links:
  Factory  $EXPL/address/$FACTORY
  Escrow   $EXPL/address/$ESCROW
  Multisig $EXPL/address/$MULTISIG

Next steps:
  1. Mint the TapeOut circuit + open the container  (id.tapeout.link / HashPort) — wallet signatures
  2. Publish app/dist to the SiteRegistry            — wallet signatures
  3. Put the addresses into the Google Form fields and record the <=3 min demo video
EOF
